import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { HouseholdState } from '../../src/shared/types.js';

const snapshot = async (): Promise<HouseholdState> => JSON.parse(await readFile(process.env.ROOMLILT_BROWSER_DATA_FILE!, 'utf8')) as HouseholdState;

test('real browser demo: required morning yield, visible evening fairness choice, named consent, reconnect, and local repair', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#connection-label')).toHaveText('Connected locally');
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await expect(page.locator('#utterance')).toBeEnabled();
  const initial = await snapshot();
  await page.screenshot({ path: 'data/initial-1280x800.png', fullPage: true });
  await page.locator('.suggestions [data-utterance="What\'s clashing today?"]').click();
  await expect(page.locator('.conflict-card')).toHaveCount(2);
  await page.locator('.suggestions [data-utterance="Find a fair plan"]').click();
  const recommended = page.locator('.plan-card.recommended');
  await expect(recommended).toContainText('Required yield');
  await expect(recommended.locator('.plan-changes')).toContainText('Laundry');
  await expect(recommended.locator('.plan-changes')).toContainText('14:00–16:00');
  await page.screenshot({ path: 'data/morning-plans-1280x800.png', fullPage: true });
  await recommended.locator('[data-plan]').click();
  const consent = page.getByRole('dialog');
  await expect(consent).toContainText('Sam, does this work for you?');
  await consent.getByRole('button', { name: 'Decline', exact: true }).click();
  await expect(consent).not.toBeVisible();
  await expect(page.locator('#messages')).toContainText('did not consent');
  await expect(page.locator('#utterance')).toBeEnabled();
  expect(await snapshot()).toEqual(initial);
  await recommended.locator('[data-plan]').click();
  await consent.getByRole('button', { name: /Sam.*accept/ }).click();
  await expect(page.locator('.saved-badge')).toContainText('Saved locally');
  await expect(page.locator('.agreement-card')).toHaveCount(1);
  await expect(page.locator('.agreement-list')).toContainText('14:00–16:00');
  await expect(page.locator('.evening-nudge')).toContainText("Compare tonight's plans");
  const morning = await snapshot();
  expect(morning.ledger.find(entry => entry.memberId === 'sam')).toMatchObject({ yieldCount: 9, requiredYields: 7, negotiatedYields: 2, effortPoints: 20 });

  await page.locator('.suggestions [data-utterance="Who gets the living room tonight?"]').click();
  await expect(recommended).toContainText('Fairest');
  await expect(recommended).toContainText('Recommended');
  await expect(recommended.locator('.plan-reason')).toContainText('9');
  await expect(recommended.locator('.plan-reason')).toContainText('Leo');
  await expect(recommended.locator('.plan-changes')).toContainText('Leo');
  await expect(recommended.locator('.room-change')).toContainText('Living room → Private study');
  const lowest = page.locator('.plan-card').filter({ has: page.locator('.plan-badge', { hasText: /^Lowest disruption$/ }) });
  await expect(lowest).toHaveCount(1);
  await expect(lowest.locator('.plan-changes')).toContainText('Sam');
  await expect(lowest.locator('.time-change')).toContainText('20:00–22:00');
  const scores = async (which: typeof recommended) => (await which.locator('.plan-scores b').allTextContents()).map(Number);
  const fairScores = await scores(recommended);
  const lowScores = await scores(lowest);
  expect(lowScores[0]).toBeLessThan(fairScores[0]);
  expect(fairScores[1]).toBeLessThan(lowScores[1]);
  await page.screenshot({ path: 'data/plans-1280x800.png', fullPage: true });
  await lowest.locator('[data-plan]').click();
  await expect(consent).toContainText('Sam, does this work for you?');
  await consent.getByRole('button', { name: 'Decline', exact: true }).click();
  await expect(page.locator('#utterance')).toBeEnabled();
  expect(await snapshot()).toEqual(morning);
  await recommended.locator('[data-plan]').click();
  await expect(consent).toContainText('Leo, does this work for you?');
  await page.screenshot({ path: 'data/consent-1280x800.png', fullPage: true });
  await consent.getByRole('button', { name: /Leo.*accept/ }).click();
  await expect(page.locator('.agreement-card')).toHaveCount(2);
  await expect(page.locator('.agreement-list')).toContainText('Evening reading');
  await expect(page.locator('.agreement-list')).toContainText('Private study');
  const saved = await snapshot();
  expect(saved.activities.find(activity => activity.id === 'sam-game')?.start).toBe(19 * 60);
  await page.locator('.suggestions [data-utterance="Is it fair?"]').click();
  await expect(page.locator('.ledger-member')).toHaveCount(3);
  await expect(page.locator('[data-member="sam"]')).toContainText('7 required · 2 negotiated');
  await expect(page.locator('[data-member="sam"]')).toContainText('20 effort points');
  await expect(page.locator('[data-member="sam"]')).toContainText('9');
  await page.screenshot({ path: 'data/ledger-1280x800.png', fullPage: true });

  // Reload creates a fresh real MCP client/session; the HTTP client test also restarts the server.
  await page.reload();
  await expect(page.locator('#connection-label')).toHaveText('Connected locally');
  await page.locator('.suggestions [data-utterance="What did we agree?"]').click();
  await expect(page.locator('.agreement-card')).toHaveCount(2);
  expect(await snapshot()).toEqual(saved);
  await page.locator('.suggestions [data-utterance="Leo\'s meeting runs 30 minutes late"]').click();
  await expect(page.locator('.kept-agreements')).toContainText('2 earlier agreements kept');
  await expect(page.locator('.kept-agreements')).toContainText('Laundry');
  await expect(page.locator('.kept-agreements')).toContainText('Evening reading');
  await expect(recommended.locator('.plan-changes')).toContainText('Video meeting');
  await expect(recommended.locator('.plan-changes')).not.toContainText('Laundry');
  await expect(recommended.locator('.room-change')).toContainText('Private study');
  await page.screenshot({ path: 'data/repair-1280x800.png', fullPage: true });
  await recommended.locator('[data-plan]').click();
  await expect(consent).toContainText('Leo, does this work for you?');
  await consent.getByRole('button', { name: /Leo.*accept/ }).click();
  await expect(page.locator('.agreement-card')).toHaveCount(3);
  await expect(page.locator('.agreement-list')).toContainText('14:00–16:00');
  const repaired = await snapshot();
  for (const id of ['sam-laundry', 'sam-class', 'sam-game', 'leo-reading']) {
    expect(repaired.activities.find(activity => activity.id === id)).toEqual(saved.activities.find(activity => activity.id === id));
  }
  expect(repaired.activities.find(activity => activity.id === 'leo-meeting')).toMatchObject({ end: 690, resourceId: 'private-study' });
  for (const agreement of saved.agreements) expect(repaired.agreements.find(item => item.id === agreement.id)).toEqual(agreement);
  await page.locator('#protocol-inspector > summary').click();
  const protocol = page.locator('#protocol-traffic');
  await expect(protocol).toContainText('initialize');
  await expect(protocol).toContainText('"protocolVersion": "2025-11-25"');
  await expect(protocol).toContainText('tools/list');
  await expect(protocol).toContainText('tools/call');
  await expect(protocol).toContainText('elicitation/create');
  await page.locator('.suggestions [data-utterance="What\'s clashing today?"]').click();
  await expect(page.locator('#messages')).toContainText('No clashes for this date.');
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test('text fallback and narrow viewport keep the ledger and essential controls usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('#connection-label')).toHaveText('Connected locally');
  await page.getByRole('textbox', { name: 'Talk to RoomLilt' }).fill('Hey Alexa, is it fair?');
  await page.getByRole('button', { name: 'Send message' }).click();
  await expect(page.locator('.ledger-member')).toHaveCount(3);
  await expect(page.locator('.ledger-list')).toContainText('required');
  await expect(page.locator('.ledger-list')).toContainText('negotiated');
  await expect(page.locator('.ledger-list')).toContainText('effort points');
  await expect(page.locator('.ledger-list')).not.toContainText('disruption min');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'data/mobile-390x844.png', fullPage: true });
});
